export function lang() {
  return prefs.get().lang;
}

export function t(key, vars = {}) {
  const table = STRINGS[lang()] || STRINGS.id;
  let text = table[key] ?? STRINGS.en[key] ?? key;
  for (const [name, value] of Object.entries(vars)) text = text.replaceAll(`{${name}}`, value);
  return text;
}

// Pick the right language from a { id, en } object.
export function L(obj) {
  if (obj == null) return '';
  if (typeof obj === 'string') return obj;
  return obj[lang()] ?? obj.id ?? obj.en ?? '';
}

export function fmtDate(iso, opts = { day: 'numeric', month: 'short' }) {
  const [y, m, d] = iso.split('-').map(Number);
  return new Date(y, m - 1, d).toLocaleDateString(lang() === 'id' ? 'id-ID' : 'en-GB', opts);
}
